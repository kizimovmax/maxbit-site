/**
 * Наполнение сайта рабочими текстами (v0.3 — задание «доработка содержания и сборка сайта v0.3»).
 * Запуск: панель «MAXBIT → Наполнение» (кнопка, администратор) или WP-CLI `wp maxbit seed`.
 *
 * Версионно и безопасно для ручных правок:
 * - у каждого материала ключ _mb_seed_key и хэш последнего сидового текста _mb_seed_hash;
 * - если материал не правили вручную (его текст совпадает с хэшем прошлого сида, либо хэша ещё нет
 *   и запись не редактировалась после создания), он обновляется до новой версии;
 * - если правили вручную — запись не трогается, в журнал пишется предупреждение, новая версия ждёт
 *   решения владельца (_mb_seed_pending);
 * - ничего не удаляется; статус записи (черновик/опубликовано) и флаг допуска не меняются.
 * Имена клиентов в код не включены.
 */

function maxbit_seed_log( string $line ): void {
	$GLOBALS['maxbit_seed_log'][] = $line;
	if ( defined( 'WP_CLI' ) && WP_CLI ) {
		WP_CLI::log( $line );
	}
}

function maxbit_seed_find( string $key ): ?int {
	$ids = get_posts( array( 'post_type' => array( 'page', 'post', 'mb_solution', 'mb_project' ), 'post_status' => array( 'publish', 'draft', 'private', 'pending', 'future', 'trash' ), 'numberposts' => 1, 'fields' => 'ids', 'meta_key' => '_mb_seed_key', 'meta_value' => $key ) );
	return $ids ? (int) $ids[0] : null;
}

function maxbit_seed_hash( array $post ): string {
	return md5( ( $post['post_title'] ?? '' ) . '|' . ( $post['post_content'] ?? '' ) . '|' . ( $post['post_excerpt'] ?? '' ) );
}

/** Мета, которую сид вправе обновлять у нетронутых записей (SEO и служебные подписи). Допуск и статус — никогда. */
function maxbit_seed_updatable_meta(): array {
	return array( '_mb_seo_title', '_mb_seo_description', '_mb_editorial_status', '_mb_noindex' );
}

function maxbit_seed_item( string $key, array $post, array $meta = array() ): int {
	$existing = maxbit_seed_find( $key );
	$new_hash = maxbit_seed_hash( $post );
	if ( ! $existing ) {
		$post['meta_input'] = array_merge( array( '_mb_seed_key' => $key, '_mb_seed_hash' => $new_hash ), $meta );
		$id = wp_insert_post( $post, true );
		if ( is_wp_error( $id ) ) {
			maxbit_seed_log( 'ОШИБКА ' . $key . ': ' . $id->get_error_message() ); return 0;
		}
		maxbit_seed_log( "  + создано: $key (#$id)" );
		return $id;
	}
	$cur = get_post( $existing );
	/* связи и допуск — только если ещё не заданы */
	foreach ( $meta as $mk => $mv ) {
		if ( ! in_array( $mk, maxbit_seed_updatable_meta(), true ) && ! metadata_exists( 'post', $existing, $mk ) ) {
			update_post_meta( $existing, $mk, $mv );
		}
	}
	$stored = (string) get_post_meta( $existing, '_mb_seed_hash', true );
	if ( $stored === $new_hash ) {
		maxbit_seed_log( "  = актуально: $key (#$existing)" );
		return $existing;
	}
	$cur_hash  = maxbit_seed_hash( array( 'post_title' => $cur->post_title, 'post_content' => $cur->post_content, 'post_excerpt' => $cur->post_excerpt ) );
	$untouched = ( $stored && $stored === $cur_hash )
		|| ( ! $stored && abs( strtotime( $cur->post_modified_gmt ) - strtotime( $cur->post_date_gmt ) ) < 180 )
		|| ( ! $stored && '' === trim( $cur->post_content ) )
		|| '1' === (string) get_post_meta( $existing, '_mb_seed_accept', true );   // явное согласие владельца принять сидовую версию
	if ( ! $untouched ) {
		update_post_meta( $existing, '_mb_seed_pending', $new_hash );
		maxbit_seed_log( "  ! правилось вручную — не трогаю: $key (#$existing). Новая версия текста не применена; сверьте в редакторе." );
		return $existing;
	}
	$upd = array( 'ID' => $existing );
	foreach ( array( 'post_title', 'post_content', 'post_excerpt', 'post_name', 'post_parent' ) as $f ) {
		if ( array_key_exists( $f, $post ) ) {
			$upd[ $f ] = $post[ $f ];
		}
	}
	$r = wp_update_post( wp_slash( $upd ), true );
	if ( is_wp_error( $r ) ) {
		maxbit_seed_log( 'ОШИБКА обновления ' . $key . ': ' . $r->get_error_message() ); return $existing;
	}
	foreach ( $meta as $mk => $mv ) {
		if ( in_array( $mk, maxbit_seed_updatable_meta(), true ) ) {
			update_post_meta( $existing, $mk, $mv );
		}
	}
	update_post_meta( $existing, '_mb_seed_hash', $new_hash );
	delete_post_meta( $existing, '_mb_seed_pending' );
	delete_post_meta( $existing, '_mb_seed_accept' );
	maxbit_seed_log( "  ~ обновлено до текущей версии: $key (#$existing)" );
	return $existing;
}

/* Хелперы блочной разметки */
function maxbit_sb_p( string $t, string $cls = '' ): string {
	$a = $cls ? ' {"className":"' . $cls . '"}' : '';
	$c = $cls ? ' class="' . $cls . '"' : '';
	return "<!-- wp:paragraph$a -->\n<p$c>$t</p>\n<!-- /wp:paragraph -->\n";
}
function maxbit_sb_h( int $l, string $t, string $cls = '' ): string {
	$attrs = array( 'level' => $l );
	if ( $cls ) {
		$attrs['className'] = $cls;
	}
	$c = $cls ? ' class="' . $cls . '"' : '';
	$j = json_encode( $attrs );
	if ( 2 === $l && ! $cls ) {
		return "<!-- wp:heading -->\n<h2 class=\"wp-block-heading\">$t</h2>\n<!-- /wp:heading -->\n";
	}
	return "<!-- wp:heading $j -->\n<h$l class=\"wp-block-heading$c\">$t</h$l>\n<!-- /wp:heading -->\n";
}
function maxbit_sb_list( array $items, bool $ordered = false ): string {
	$tag = $ordered ? 'ol' : 'ul';
	$a   = $ordered ? ' {"ordered":true}' : '';
	$out = "<!-- wp:list$a -->\n<$tag class=\"wp-block-list\">";
	foreach ( $items as $i ) {
		$out .= "<!-- wp:list-item -->\n<li>$i</li>\n<!-- /wp:list-item -->\n";
	}
	return $out . "</$tag>\n<!-- /wp:list -->\n";
}
function maxbit_sb_group( string $inner, string $cls, bool $panel = false ): string {
	$attrs = array( 'className' => $cls . ( $panel ? ' is-style-panel' : '' ) );
	$attrs['layout'] = array( 'type' => 'constrained' );
	$j = json_encode( $attrs );
	$c = $cls . ( $panel ? ' is-style-panel' : '' );
	return "<!-- wp:group $j -->\n<div class=\"wp-block-group $c\">$inner</div>\n<!-- /wp:group -->\n";
}
function maxbit_sb_section( string $inner, string $cls = '' ): string {
	$c = trim( 'mb-section ' . $cls );
	return "<!-- wp:group {\"className\":\"$c\",\"layout\":{\"type\":\"constrained\"}} -->\n<div class=\"wp-block-group $c\">$inner</div>\n<!-- /wp:group -->\n";
}
function maxbit_sb_columns( array $cols, string $cls ): string {
	$out = "<!-- wp:columns {\"className\":\"$cls\"} -->\n<div class=\"wp-block-columns $cls\">";
	foreach ( $cols as $col ) {
		$out .= "<!-- wp:column -->\n<div class=\"wp-block-column\">$col</div>\n<!-- /wp:column -->\n";
	}
	return $out . "</div>\n<!-- /wp:columns -->\n";
}
function maxbit_sb_tile( string $h, string $p ): string {
	return maxbit_sb_h( 3, $h ) . maxbit_sb_p( $p );
}
function maxbit_sb_buttons( array $btns, string $cls = '' ): string {
	$c = trim( 'wp-block-buttons ' . $cls );
	$j = $cls ? " {\"className\":\"$cls\"}" : '';
	$out = "<!-- wp:buttons$j -->\n<div class=\"$c\">";
	foreach ( $btns as $b ) {
		[ $label, $url, $outline ] = $b + array( '', '#', false );
		$style = $outline ? ' {"className":"is-style-outline"}' : '';
		$sc = $outline ? ' is-style-outline' : '';
		$out .= "<!-- wp:button$style -->\n<div class=\"wp-block-button$sc\"><a class=\"wp-block-button__link wp-element-button\" href=\"$url\">$label</a></div>\n<!-- /wp:button -->\n";
	}
	return $out . "</div>\n<!-- /wp:buttons -->\n";
}
function maxbit_sb_sc( string $sc ): string {
	return "<!-- wp:shortcode -->\n$sc\n<!-- /wp:shortcode -->\n";
}
function maxbit_sb_html( string $html ): string {
	return "<!-- wp:html -->\n$html\n<!-- /wp:html -->\n";
}
function maxbit_sb_head( string $h2, string $p = '' ): string {
	return maxbit_sb_group( maxbit_sb_h( 2, $h2 ) . ( $p ? maxbit_sb_p( $p ) : '' ), 'mb-section__head' );
}
/** Секция «Ответы на вопросы»: видимые <details> (их же читает FAQPage-разметка). */
function maxbit_sb_faq( array $qa, string $h = 'Ответы на вопросы' ): string {
	$inner = maxbit_sb_h( 2, $h );
	foreach ( $qa as $q => $a ) {
		$inner .= maxbit_sb_details( $q, $a );
	}
	return maxbit_sb_group( $inner, 'mb-faq' );
}
function maxbit_sb_details( string $q, string $a ): string {
	return "<!-- wp:details -->\n<details class=\"wp-block-details\"><summary>$q</summary>" . maxbit_sb_p( $a ) . "</details>\n<!-- /wp:details -->\n";
}

function maxbit_seed_menu( string $name, string $location, array $items ): void {
	$menu = wp_get_nav_menu_object( $name );
	if ( $menu ) {
		maxbit_seed_log( "  = меню «{$name}» есть — не трогаю" );
		return;
	}
	$menu_id = wp_create_nav_menu( $name );
	foreach ( $items as $it ) {
		wp_update_nav_menu_item( $menu_id, 0, $it + array( 'menu-item-status' => 'publish' ) );
	}
	$locations = get_theme_mod( 'nav_menu_locations', array() );
	$locations[ $location ] = $menu_id;
	set_theme_mod( 'nav_menu_locations', $locations );
	maxbit_seed_log( "  + меню «{$name}» создано" );
}

/** Точечная синхронизация существующего меню: переименовать устаревший пункт, добавить недостающий. Ничего не удаляет. */
function maxbit_seed_menu_sync( string $name, array $rename, array $add ): void {
	$menu = wp_get_nav_menu_object( $name );
	if ( ! $menu ) {
		return;
	}
	$items = wp_get_nav_menu_items( $menu->term_id ) ?: array();
	$titles = array();
	foreach ( $items as $it ) {
		$titles[] = $it->title;
		if ( isset( $rename[ $it->title ] ) ) {
			wp_update_nav_menu_item( $menu->term_id, $it->db_id, array(
				'menu-item-title' => $rename[ $it->title ], 'menu-item-status' => 'publish',
				'menu-item-type' => $it->type, 'menu-item-object' => $it->object, 'menu-item-object-id' => $it->object_id, 'menu-item-position' => (int) $it->menu_order,
			) );
			maxbit_seed_log( "  ~ меню «{$name}»: «{$it->title}» → «{$rename[ $it->title ]}»" );
			$titles[] = $rename[ $it->title ];
		}
	}
	foreach ( $add as $it ) {
		if ( in_array( $it['menu-item-title'], $titles, true ) ) {
			continue;
		}
		wp_update_nav_menu_item( $menu->term_id, 0, $it + array( 'menu-item-status' => 'publish' ) );
		maxbit_seed_log( "  + меню «{$name}»: добавлен пункт «{$it['menu-item-title']}»" );
	}
}

